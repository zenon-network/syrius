/// Supported wallet text scaling presets.
enum TextScaling {
  /// Follow the operating system text scale factor.
  system,

  /// Smaller text scaling.
  small,

  /// Default 1.0 text scaling.
  normal,

  /// Larger text scaling.
  large,

  /// Maximum text scaling.
  huge,
}

/// Supported wallet UI locales.
enum LocaleType {
  /// English locale.
  english,
}
